# Показываем, как тексты разделились на parent и child.
print("Разбиение документов:")

for document_index, document in enumerate(documents, start=1):
    parents = parent_splitter.split_documents([document])

    for parent_index, parent in enumerate(parents, start=1):
        children = child_splitter.split_documents([parent])

        print(
            f"\nДокумент {document_index}, "
            f"parent {parent_index}, "
            f"child-фрагментов: {len(children)}"
        )
        print("Parent:", parent.page_content)

        for child_index, child in enumerate(children, start=1):
            print(f"  Child {child_index}: {child.page_content}")


# Для этого учебного примера каждый исходный документ короткий,
# поэтому он должен дать по одному parent.
# При повторном запуске эти же ID обновляют родительские записи в SQLStore.
parent_ids = [
    f"{doc.metadata['source']}:{doc.metadata['section']}"
    for doc in documents
]

retriever.add_documents(
    documents,
    ids=parent_ids,
)
